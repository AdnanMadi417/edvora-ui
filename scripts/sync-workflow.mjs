#!/usr/bin/env node
// Copies the application workflow (stages, statuses, who acts, next actions)
// from unibexs-backend's production seed into src/config/workflow.generated.ts,
// so the frontend's stage codes and "whose turn" rule match the backend.
//
// Usage: npm run sync:workflow -- [path/to/unibexs-backend]
// Default path: ../unibexs-org/unibexs-backend (or $UNIBEXS_BACKEND_DIR).

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(
  process.argv[2] ?? process.env.UNIBEXS_BACKEND_DIR ?? join(root, "..", "unibexs-org", "unibexs-backend"),
);
const seedPath = join(backend, "scripts", "prod-seed.json");
const seed = JSON.parse(readFileSync(seedPath, "utf8"));

let commit = "unknown";
try {
  commit = execSync("git rev-parse --short HEAD", { cwd: backend }).toString().trim();
} catch {
  // Not a git checkout; keep "unknown".
}

// Backend role ids (app/core/enums.py UserRole).
const ACTOR = { 1: "admin", 2: "advisor", 3: "account_manager", 4: "data_entry", 5: "reviewer" };
const actionFor = (stageName, statusName, actor) =>
  seed.next_actions.find((a) => a.stage_name === stageName && a.status_name === statusName && a.actor === actor)?.name ?? null;

const stages = [...seed.stages]
  .sort((a, b) => a.order_index - b.order_index)
  .map((stage) => ({
    code: stage.code,
    name: stage.name,
    order: stage.order_index,
    statuses: stage.statuses.map((s) => ({
      code: s.code,
      name: s.name,
      note: s.note ?? null,
      actor: ACTOR[s.allowed_actor] ?? null,
      isDefault: !!s.is_default_status_stage,
      requiresReason: !!s.is_requires_reason,
      requiresDocuments: !!s.is_requires_document_selection,
      advancesStage: !!s.is_triggers_stage_advance,
      managerNext: s.manager_next_status_codes ?? [],
      advisorAction: actionFor(stage.name, s.name, 2),
      managerAction: actionFor(stage.name, s.name, 3),
    })),
  }));

const out = `// GENERATED by scripts/sync-workflow.mjs from unibexs-backend scripts/prod-seed.json
// at backend commit ${commit}. Do not edit by hand: run \`npm run sync:workflow\`.
//
// The application workflow as the backend defines it: stages in order, each
// status's code, name and the role whose turn it is (allowed_actor).

export type WorkflowActor = "admin" | "advisor" | "account_manager" | "data_entry" | "reviewer";

export interface WorkflowStatus {
  code: string;
  name: string;
  note: string | null;
  /** Whose turn it is in this status (backend allowed_actor). */
  actor: WorkflowActor | null;
  isDefault: boolean;
  requiresReason: boolean;
  requiresDocuments: boolean;
  advancesStage: boolean;
  /** Statuses a manager can move the application to from here. */
  managerNext: string[];
  advisorAction: string | null;
  managerAction: string | null;
}

export interface WorkflowStage {
  code: string;
  name: string;
  order: number;
  statuses: WorkflowStatus[];
}

export const WORKFLOW_SOURCE = ${JSON.stringify({ repo: "unibexs-backend", file: "scripts/prod-seed.json", commit })} as const;

export const WORKFLOW: readonly WorkflowStage[] = ${JSON.stringify(stages, null, 2)};
`;

const target = join(root, "src", "config", "workflow.generated.ts");
writeFileSync(target, out);
try {
  execSync(`npx prettier --write "${target}"`, { cwd: root, stdio: "ignore" });
} catch {
  // Formatting is cosmetic; the file is valid without it.
}
const count = stages.reduce((n, s) => n + s.statuses.length, 0);
console.log(`Wrote ${target}: ${stages.length} stages, ${count} statuses (backend ${commit}).`);
